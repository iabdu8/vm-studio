const DEFAULT_LANGUAGE = "en";

export function getLanguage() {
  try {
    const saved = globalThis.localStorage?.getItem(LANGUAGE_KEY);
    return saved === "ar" || saved === "en" ? saved : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function getLocale(language = getLanguage()) {
  return language === "en" ? "en" : "ar-SA";
}

export function getDirection(language = getLanguage()) {
  return language === "en" ? "ltr" : "rtl";
}

export function applyDocumentLanguage(language = getLanguage()) {
  if (!globalThis.document?.documentElement) return;
  document.documentElement.lang = getLocale(language);
  document.documentElement.dir = getDirection(language);
}

export function setLanguage(language) {
  const next = language === "en" ? "en" : "ar";
  try {
    globalThis.localStorage?.setItem(LANGUAGE_KEY, next);
  } catch {
    // Keep the in-memory UI update even when storage is unavailable.
  }
  applyDocumentLanguage(next);
  globalThis.window?.dispatchEvent(new CustomEvent("vismo:language", { detail: next }));
}

export const locale = getLocale();
export const direction = getDirection();

export function t(path, fallback = "") {
  const language = getLanguage();
  return path.split(".").reduce((obj, key) => obj?.[key], translations[language]) ?? fallback;
}

export function roleLabel(role) {
  return t(`roles.${role}`, role || "");
}

export function useLanguage() {
  const [language, setLanguageState] = useState(getLanguage);
  useEffect(() => {
    applyDocumentLanguage(language);
    const onChange = (event) => setLanguageState(event.detail ?? getLanguage());
    window.addEventListener("vismo:language", onChange);
    return () => window.removeEventListener("vismo:language", onChange);
  }, [language]);
  return {
    language,
    direction: getDirection(language),
    locale: getLocale(language),
    setLanguage,
    toggleLanguage: () => setLanguage(language === "ar" ? "en" : "ar"),
  };
}
